num = int(input('Enter a number > '))

if num == 100:
    print('This number is Equal to 100')
    
if num > 100:
    print('This number is More than 100')

if num < 100:
    print('This number is Less than 100')

if num >= 100:
    print('This number is More than or equal to 100')

if num <= 100:
    print('This number is Less than or equal to 100')

if num != 100:
    print('This number is Not 100')